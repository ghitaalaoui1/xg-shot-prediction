import { ArrowUpRight, Goal, Target, TimerReset } from 'lucide-react'

export default function XgResult({ result, loading, error, onPredict, geometry }) {
  const percent = result == null ? null : Math.max(0, Math.min(100, result * 100))
  return (
    <section className="result-card">
      <div className="result-head"><div><span className="eyebrow">MODEL OUTPUT</span><h3>Expected goals</h3></div><span className="model-pill"><i /> LOGISTIC REGRESSION</span></div>
      <div className="result-main">
        <div className="xg-value">{percent == null ? '—' : result.toFixed(3)}<span>{percent == null ? 'Awaiting prediction' : 'xG probability'}</span></div>
        <div className="ring-wrap"><div className="ring" style={{ '--progress': `${percent ?? 0}%` }}><div><b>{percent == null ? '—' : `${percent.toFixed(1)}%`}</b><small>GOAL CHANCE</small></div></div></div>
      </div>
      <div className="result-meter"><div style={{ width: `${percent ?? 0}%` }} /></div>
      <div className="result-stats"><div><Target size={15}/><span>Distance</span><b>{geometry.distance.toFixed(1)} yd</b></div><div><ArrowUpRight size={15}/><span>Shot angle</span><b>{(geometry.angle * 180 / Math.PI).toFixed(1)}°</b></div></div>
      {error && <div className="api-error"><b>Prediction failed</b><span>{error}</span></div>}
      <button className="predict-button" onClick={onPredict} disabled={loading}>{loading ? <><span className="spinner" /> Calculating…</> : <><Goal size={17} /> Calculate xG <ArrowUpRight size={16} /></>}</button>
      <div className="result-foot"><TimerReset size={13}/> Prediction generated by your FastAPI model</div>
    </section>
  )
}
